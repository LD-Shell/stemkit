const PAGES = TABLE.pages;
const PACKAGES = TABLE.packages;

/** The address of a manual page; a few pages moved on docs.lammps.org since this release. */
function pageUrl(page) {
  return `${LAMMPS_DOCS}${TABLE.pageUrls[page] || page}.html`;
}

/** 'fix nvt' style key: the command that selects the style, then the style. */
function keyFor(kind, name) {
  return kind === 'command' ? name : `${KIND_COMMAND.get(kind)} ${name}`;
}

/**
 * Split what the caller passed into a kind and a name. Accepts
 * ('fix', 'nvt'), ('pair_style', 'lj/cut'), ('pair', 'lj/cut'),
 * ('fix nvt'), ('units') and ('units', '') alike.
 */
function split(command, style) {
  let c = String(command == null ? '' : command).trim();
  let s = style == null ? '' : String(style).trim();
  if (!s && /\s/.test(c)) {
    const parts = c.split(/\s+/);
    // 'atom_style body nparticle', 'read_dump format native': two-word commands.
    const two = parts.length > 2 ? `${parts[0]} ${parts[1]}` : '';
    if (two && KIND_OF_COMMAND.has(two)) {
      c = two;
      s = parts[2];
    } else {
      c = parts[0];
      s = parts[1] || '';
    }
  }
  if (s) {
    const kind = styleKind(c);
    if (kind) return { kind, name: s };
    return null;
  }
  return c ? { kind: 'command', name: c } : null;
}

/** The row for a plain (unsuffixed) name, or null. */
function rawRow(kind, name) {
  const rows = TABLE.kinds[kind];
  return rows && Object.prototype.hasOwnProperty.call(rows, name) ? rows[name] : null;
}

/**
 * Resolve a kind and name to the table: the row, the plain name, the
 * accelerator suffix when the name has one, and whether that variant exists.
 */
function resolve(kind, name) {
  let row = rawRow(kind, name);
  if (row) return { row, base: name, suffix: '', exists: !(row[3] & 1) && !(row[3] & 2) };
  const m = ACCEL_SUFFIX.exec(name);
  if (!m) return null;
  const base = name.slice(0, m.index);
  row = rawRow(kind, base);
  if (!row) return null;
  const letter = ACCEL_BY_SUFFIX.get(m[1]).letter;
  const exists = row[2].includes(letter) && (!m[2] || row[2].includes('K'));
  return { row, base, suffix: m[1] + (m[2] || ''), exists };
}

function rowPackages(row) {
  const p = row[1];
  if (p === -1) return [];
  return (Array.isArray(p) ? p : [p]).map(i => PACKAGES[i]);
}

function rowAccelerators(row) {
  return ACCELERATORS.filter(a => row[2].includes(a.letter)).map(a => a.suffix);
}

/**
 * The documentation page of a command or style.
 *
 * Styles resolve through the `.. index::` entries of the LAMMPS manual, so
 * `fix nvt`, `fix npt` and `fix nph` all give fix_nh.html and every
 * accelerated variant gives its plain style's page. A style the reference
 * does not know gives the page of the command that sets it (pair_style.html);
 * an unknown command gives null.
 *
 * @param {string} command 'fix', 'pair_style', 'units', or 'fix nvt'
 * @param {string} [style] 'nvt', 'lj/cut/coul/long', 'lj/cut/omp'
 * @returns {string|null} https://docs.lammps.org/<page>.html
 */
export function lammpsDocUrl(command, style) {
  const q = split(command, style);
  if (!q) return null;
  const r = resolve(q.kind, q.name);
  if (r && r.row[0] > -1) return pageUrl(PAGES[r.row[0]]);
  if (q.kind !== 'command') {
    const cmd = rawRow('command', KIND_COMMAND.get(q.kind));
    if (cmd && cmd[0] > -1) return pageUrl(PAGES[cmd[0]]);
  }
  return null;
}

/**
 * Whether LAMMPS 29 Aug 2024 has this command or style. Accelerated
 * variants count only when that variant is compiled somewhere in LAMMPS
 * (`lj/cut/omp` yes, `lj/cut/coul/wolf/gpu` no). Names that are only
 * documented give false, and so do removed names, except the few LAMMPS
 * still runs (`reset_ids` runs as `reset_atoms id`, `box` is ignored):
 * commandInfo().removed says which.
 *
 * With `packages` (the packages of a build, as `lmp -h` lists them under
 * "Installed packages"), the answer is whether that build has it; `flags`
 * (its "Active compile time flags", like LAMMPS_ZSTD) rules out the few
 * styles that need an optional library.
 *
 * @param {string} command
 * @param {string} [style]
 * @param {{packages?: string[], flags?: string[]}} [options]
 * @returns {boolean}
 */
export function styleExists(command, style, { packages = null, flags = null } = {}) {
  const q = split(command, style);
  if (!q) return false;
  const r = resolve(q.kind, q.name);
  if (!r || !r.exists) return false;
  const removed = TABLE.removed[`${q.kind} ${r.base}`];
  if (removed && !RUNS.has(removed[1])) return false;
  const flag = TABLE.compileFlags[`${q.kind} ${r.base}`];
  if (flags && flag && !flags.includes(flag)) return false;
  if (!packages) return true;
  const have = new Set(packages);
  return neededPackages(q.kind, r).every(p => have.has(p));
}

function neededPackages(kind, r) {
  const own = rowPackages(r.row);
  // A name several packages register is available with any one of them;
  // report the first.
  const base = [...(own.length > 1 ? [own[0]] : own), ...(TABLE.requires[`${kind} ${r.base}`] || [])];
  if (!r.suffix) return [...new Set(base)];
  return [...new Set([...base, ...variantPackages(kind, r), ...(TABLE.requires[`${kind} ${r.base}/${r.suffix}`] || [])])];
}

/** The packages that register an accelerated variant: usually the accelerator's. */
function variantPackages(kind, r) {
  const listed = TABLE.variantPackages && TABLE.variantPackages[`${kind} ${r.base}/${r.suffix}`];
  return listed ? listed : [ACCEL_BY_SUFFIX.get(r.suffix.split('/')[0]).package];
}

let details = null;
let detailsPromise = null;

/**
 * Load the keyword, unit and default tables (lammps-docs.js, about 85 kB).
 * After it resolves, {@link commandInfo} includes `keywords`, `units`,
 * `choices`, `attributes` and `defaults`.
 *
 * @returns {Promise<void>}
 */
export function loadLammpsDetails() {
  if (!detailsPromise) {
    detailsPromise = import('./lammps-docs.js').then(m => { details = m.default; });
  }
  return detailsPromise;
}

/** Whether {@link loadLammpsDetails} has finished. */
export function lammpsDetailsLoaded() {
  return details !== null;
}

/**
 * Everything the reference knows about one command or style.
 *
 * @param {string} command 'fix', 'pair_style', 'units', or 'fix nvt'
 * @param {string} [style]
 * @returns {null|{
 *   key: string, kind: string, command: string, style: string, name: string,
 *   base: string, accelerator: string|null, alias?: string, exists: boolean,
 *   url: string|null, page: string|null, package: string|null, packages: string[], builtin: boolean,
 *   accelerators: string[], category?: string, compileFlag?: string, syntax: string, args: string[]|null,
 *   keywords: {name: string, values: string[]|null, choices?: string[], units?: Object<string,string>,
 *     words?: string[]}[], attributes?: string[],
 *   units: Object<string,string>, choices: Object<string,string[]>,
 *   defaults: Object<string,string>|string[]|null,
 *   summary: string, removed?: {since: string, status: 'renamed'|'ignored'|'stops'|'unknown',
 *     replacement: string, renamed?: string, note: string}
 * }}
 *   key: how the line starts in an input ('fix nvt', 'pair_style lj/cut/omp', 'units');
 *   name: the name as asked; base: without the accelerator suffix;
 *   exists: LAMMPS has it (see styleExists); package: the package that provides
 *   this exact name (the accelerator's for a variant), null for the core;
 *   packages: every package a build needs for it; builtin: run by the input
 *   reader or the core itself (units, pair_style none), so `lmp -h` does not
 *   list it; accelerators: the variants of
 *   the plain style; syntax: the skeleton from the manual with this style filled in;
 *   args: the style's argument names; units: value name -> the quantity it is
 *   measured in ('time', 'distance', ...); choices: positional value -> the
 *   words it accepts; attributes: the words the style takes as arguments
 *   (dump custom: id, type, x...; compute property/atom: id, mol...), and
 *   keyword.words the same for a keyword (thermo_style custom: step, temp...);
 *   keywords, units, choices, attributes, defaults: once
 *   loadLammpsDetails() has resolved, else empty; removed: for names LAMMPS
 *   dropped, what it does with them now (renamed: runs as `renamed` with a
 *   warning; ignored: prints a message; stops: ends with an error; unknown:
 *   the name is not registered any more) and what to write instead.
 */
export function commandInfo(command, style) {
  const q = split(command, style);
  if (!q) return null;
  const r = resolve(q.kind, q.name);
  if (!r) return null;
  return build(q.kind, q.name, r);
}

function build(kind, name, r) {
  const { row, base, suffix } = r;
  const command = kind === 'command' ? base : KIND_COMMAND.get(kind);
  const page = row[0] > -1 ? PAGES[row[0]] : null;
  const alias = TABLE.aliases[`${kind} ${base}`];
  const own = rowPackages(row);
  const accel = suffix ? (variantPackages(kind, r)[0] || null) : null;
  const info = {
    key: keyFor(kind, name),
    kind,
    command,
    style: kind === 'command' ? '' : name,
    name,
    base,
    accelerator: suffix ? suffix.split('/')[0] : null,
    exists: r.exists,
    url: page ? pageUrl(page) : null,
    page,
    package: accel || own[0] || (TABLE.requires[`${kind} ${base}`] || [])[0] || null,
    packages: neededPackages(kind, r),
    builtin: Boolean(row[3] & 4),
    accelerators: rowAccelerators(row),
    syntax: skeleton(kind, command, base, page),
    args: styleArgs(kind, base, alias, page),
    keywords: [],
    units: {},
    choices: {},
    defaults: null,
    summary: summaryOf(kind, base, alias)
  };
  if (alias) info.alias = alias;
  if (TABLE.compileFlags[`${kind} ${base}`]) info.compileFlag = TABLE.compileFlags[`${kind} ${base}`];
  if (kind === 'command' && row[4] !== undefined) info.category = TABLE.categories[row[4]];
  const removed = TABLE.removed[`${kind} ${base}`];
  if (removed) {
    const [since, status, replacement = '', renamed = ''] = removed;
    const rep = replacement ? keyFor(replacement.split(' ')[0], replacement.slice(replacement.indexOf(' ') + 1)) : '';
    info.exists = RUNS.has(status);
    info.removed = { since, status, replacement: rep, note: removedNote(since, status, rep, renamed) };
    if (renamed) info.removed.renamed = renamed;
  }
  if (details && page && details[page]) {
    const d = details[page];
    const words = d.w || {};
    info.keywords = (d.k || []).map(([n, values, units, closed]) => {
      const kw = { name: n, values: values ? values.slice() : null };
      if (closed && values && values.length === 1) kw.choices = values[0].split('|');
      if (units) kw.units = { ...units };
      if (words[n]) kw.words = words[n].slice();
      return kw;
    });
    const styleWords = words[base] || (alias && words[alias]) || words[''];
    if (styleWords) info.attributes = styleWords.slice();
    info.units = { ...(d.u || {}) };
    info.choices = Object.fromEntries(Object.entries(d.c || {}).map(([k, v]) => [k, v.slice()]));
    for (const kw of info.keywords) Object.assign(info.units, kw.units || {});
    info.defaults = Array.isArray(d.d) ? d.d.slice() : d.d ? { ...d.d } : null;
  }
  return info;
}

// Removed names LAMMPS still accepts.
const RUNS = new Set(['renamed', 'ignored']);

function removedNote(since, status, replacement, renamed) {
  const when = since ? ` in ${since}` : '';
  if (status === 'renamed') return `Renamed${when}: LAMMPS still runs it as ${renamed}, with a warning. Write ${renamed} instead.`;
  if (status === 'ignored') return `Removed${when}: LAMMPS ignores this line and prints a message. Delete it.`;
  const what = status === 'stops' ? 'LAMMPS stops with an error at this line.' : 'LAMMPS no longer knows this name.';
  return `Removed from LAMMPS${when}. ${what}${replacement ? ` Use ${replacement} instead.` : ''}`;
}

function summaryOf(kind, base, alias) {
  return SUMMARIES[keyFor(kind, base)] || (alias ? SUMMARIES[keyFor(kind, alias)] : '') || '';
}

function styleArgs(kind, base, alias, page) {
  if (kind === 'command' || !page) return null;
  const syn = TABLE.syntax[page];
  if (!syn || !syn.a) return null;
  const a = syn.a[base] || (alias && syn.a[alias]);
  return a ? a.slice() : null;
}

// Where the style name sits in a skeleton line: `fix ID group-ID style ...`.
const STYLE_POSITION = { fix: 3, compute: 3, dump: 3, region: 2 };
const STYLE_WORDS = /^(style|style_name|style-name|styles|stylename|bstyle)$/;

/**
 * The syntax skeleton of the manual with this style's name (and, for pair
 * styles and the like, its arguments) in place of the generic words.
 */
function skeleton(kind, command, base, page) {
  const syn = page && TABLE.syntax[page];
  // Body and reader styles are arguments of atom_style body and read_dump,
  // whose skeletons do not name them.
  if (!syn || !syn.s || kind === 'body' || kind === 'reader') return '';
  let lines = syn.s.filter(l => l.split(' ')[0] === command);
  if (!lines.length) lines = syn.s.slice();
  if (kind === 'command') return lines.join('\n');
  const pos = STYLE_POSITION[command] ?? 1;
  // Prefer a line written for this very style.
  const own = lines.filter(l => l.split(' ')[pos] === base);
  if (own.length) return own.join('\n');
  // atom_style lists arguments only for the styles that take any.
  const args = (syn.a && syn.a[base]) || (kind === 'atom' ? [] : null);
  // Lines written for other styles of the page only: build one from the
  // first line's start, this style and its arguments.
  if (!lines.some(l => STYLE_WORDS.test(l.split(' ')[pos] || ''))) {
    const start = lines[0].split(' ').slice(0, pos);
    return [...start, base, ...(args || ['args'])].join(' ');
  }
  return lines.map(l => {
    const words = l.split(' ');
    if (words[0] !== command || !words[pos]) return l;
    if (STYLE_WORDS.test(words[pos]) || (syn.a && syn.a[words[pos]])) {
      words[pos] = base;
      if (args && /^(args?|values?)$/.test(words[pos + 1] || '')) words.splice(pos + 1, 1, ...args);
      else if (args && args.length && words.length === pos + 1) words.push(...args);
    }
    return words.join(' ');
  }).join('\n');
}

/* ------------------------------------------------------------------ *
 * Listing and search
 * ------------------------------------------------------------------ */

function* allEntries(kind) {
  for (const { id } of COMMAND_KINDS) {
    if (kind && kind !== id) continue;
    for (const name of Object.keys(TABLE.kinds[id])) yield [id, name];
  }
}

/**
 * Every command and plain style (accelerated variants are listed on their
 * plain style), in reference order: kinds as in COMMAND_KINDS, names
 * alphabetically. Names that are only documented, not in the source, are
 * left out; removed names are included and marked.
 *
 * @param {{kind?: string}} [options] a kind id ('fix') or the command ('pair_style')
 * @returns {object[]} commandInfo results
 */
export function listCommands({ kind = '' } = {}) {
  const k = kind ? (styleKind(kind) || kind) : '';
  const out = [];
  for (const [id, name] of allEntries(k)) {
    const r = resolve(id, name);
    if (!r.exists && !TABLE.removed[`${id} ${name}`]) continue;
    out.push(build(id, name, r));
  }
  return out;
}

/** Levenshtein distance, cut off early once it exceeds `max`. */
function distance(a, b, max) {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  let prev = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    let best = i;
    for (let j = 1; j <= b.length; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
      if (cur[j] < best) best = cur[j];
    }
    if (best > max) return max + 1;
    prev = cur;
  }
  return prev[b.length];
}

const WORD = /[a-z0-9]+/g;

/**
 * A word reduced for comparison: British and American spellings agree
 * (minimise, minimize; neighbour, neighbor; centre, center) and common
 * endings go (thermostats, thermostat; minimisation, minimise).
 */
function stem(word) {
  let w = String(word).toLowerCase()
    .replace(/isation/g, 'ization').replace(/is(e|es|ed|ing)$/, 'iz$1').replace(/our/g, 'or').replace(/tre$/, 'ter');
  for (const end of ['ization', 'ation', 'izing', 'izes', 'ized', 'ize', 'ing', 'ies', 'es', 'ed', 's', 'e']) {
    if (w.length - end.length >= 3 && w.endsWith(end)) { w = w.slice(0, -end.length); break; }
  }
  return w;
}

const summaryStems = new Map();
function stemsOf(text) {
  if (!summaryStems.has(text)) summaryStems.set(text, (text.toLowerCase().match(WORD) || []).map(stem));
  return summaryStems.get(text);
}

/** How well a name matches the query: 0 for not at all, up to 100 for the exact name. */
function nameScore(n, key, q, words) {
  const compact = q.replace(/[\s/_-]+/g, '');
  if (n === q || key === q) return 100;
  if (n.replace(/[/_-]/g, '') === compact) return 90;
  if (n.startsWith(q) || key.startsWith(q)) return 80 - Math.min(20, n.length - q.length);
  // Every query word stems to a part of the name: `read data`, `minimise`, `neighbour`.
  const parts = n.split(/[/_-]/).map(stem);
  const qs = words.map(stem);
  if (qs.length && qs.every(w => parts.includes(w))) return qs.length === parts.length ? 95 : qs.length > 1 ? 60 : 50;
  if (n.includes(q)) return 55 - Math.min(15, n.length - q.length);
  if (words.length > 1 && words.every(w => n.includes(w))) return 50;
  if (n.length >= 4 && q.startsWith(n)) return 30;   // `temperature` finds temp
  const max = q.length <= 4 ? 1 : 2;
  const d = distance(q, n, max);
  if (d > max) return 0;
  return q.length <= 4 ? 25 : 45 - 10 * d;
}

/** How well a summary matches the query words: 0, or 10 to about 36. */
function summaryScore(summary, words) {
  if (!summary || !words.length) return 0;
  const stems = stemsOf(summary);
  let hits = 0;
  let first = stems.length;
  for (const w of words.map(stem)) {
    let at = stems.findIndex(s => s === w || (w.length > 3 && s.startsWith(w)));
    if (at > -1) hits++;
    else if (w.length > 4) {
      at = stems.findIndex(s => s.length > 4 && distance(w, s, 1) <= 1);
      if (at > -1) hits += 0.5;
    }
    if (at > -1) first = Math.min(first, at);
  }
  if (!hits) return 0;
  // Words near the start of the summary say what the thing is; later ones
  // only mention it.
  return 10 + 20 * hits / words.length + 6 * Math.max(0, 1 - first / 8);
}

/**
 * Search commands and styles: names first (exact, then prefix, then
 * containing the query, then close misspellings), then the words of
 * STEMKit's summaries, comparing British and American spellings alike.
 * `fix nvt`, `nvt`, `lj/cut`, `pair lj cut`, `thermostat`, `minimise` and
 * `lagevin` all find what they should.
 *
 * @param {string} query
 * @param {{kind?: string, limit?: number}} [options]
 * @returns {object[]} commandInfo results, best first, each with a `score`
 */
export function searchCommands(query, { kind = '', limit = 20 } = {}) {
  let q = String(query || '').trim().toLowerCase().replace(/\s+/g, ' ');
  if (!q) return [];
  let k = kind ? (styleKind(kind) || kind) : '';
  // `fix nvt`, `pair_style lj/cut`, `pair lj/cut`: a kind word in front narrows the search.
  const first = q.split(' ')[0];
  const firstKind = styleKind(first);
  if (firstKind && q.includes(' ') && (!k || k === firstKind)) {
    k = firstKind;
    q = q.slice(first.length + 1);
  }
  const words = q.match(WORD) || [];
  const scored = [];
  for (const [id, name] of allEntries(k)) {
    const r = resolve(id, name);
    const removed = TABLE.removed[`${id} ${name}`];
    if (!r.exists && !removed) continue;
    const summary = summaryOf(id, name, TABLE.aliases[`${id} ${name}`]);
    const byName = nameScore(name.toLowerCase(), keyFor(id, name).toLowerCase(), q, words);
    const bySummary = summaryScore(summary, words);
    let score = Math.max(byName, bySummary + (byName ? 5 : 0));
    if (!score) continue;
    if (removed) score -= 5;
    if (summary) score += 4;   // described by STEMKit: one of the styles people use most
    scored.push([score, id, name, r]);
  }
  scored.sort((a, b) => b[0] - a[0] || kindRank(a[1]) - kindRank(b[1]) || (a[2] < b[2] ? -1 : a[2] > b[2] ? 1 : 0));
  return scored.slice(0, limit).map(([score, id, name, r]) => ({ ...build(id, name, r), score: Math.round(score * 10) / 10 }));
}

const KIND_RANK = new Map(COMMAND_KINDS.map((k, i) => [k.id, i]));
function kindRank(id) { return KIND_RANK.get(id) ?? 99; }
