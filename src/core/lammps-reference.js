/**
 * @module core/lammps-reference
 *
 * The LAMMPS command reference behind the MD Workflow Generator: every
 * command and style of LAMMPS 29 Aug 2024 (pair, bond, angle, dihedral,
 * improper, kspace, fix, compute, dump, atom, region, minimise and run
 * styles, and the body and dump-reader styles), with its documentation page,
 * the package that provides it and the packages it needs, its
 * accelerated variants, the syntax skeleton, keyword and value names, and
 * STEMKit's own one-line summary. Also the eight unit systems.
 *
 * The tables come from the LAMMPS source (`lammps-commands.js`, generated by
 * tools/build-lammps-docs.mjs): names and packages from the style
 * registrations in src/, pages and syntax from doc/src/*.rst. Keywords,
 * value units and defaults are a separate table loaded on request with
 * {@link loadLammpsDetails}; until it has loaded, `commandInfo` returns them
 * empty. Facts only: explanations are STEMKit's words, and every entry links
 * to docs.lammps.org for the full text.
 *
 * Names are looked up the way LAMMPS looks them up: exactly, except that an
 * accelerated variant (`lj/cut/omp`, `nvt/kk/device`) resolves to its plain
 * style and says which accelerator it is. Old names LAMMPS still registers
 * (`lj/sdk`, `fix qeq/reax`) are aliases of the documented ones; names it
 * dropped carry a `removed` note.
 *
 * ```js
 * lammpsDocUrl('fix', 'npt');             // 'https://docs.lammps.org/fix_nh.html'
 * commandInfo('pair_style', 'lj/cut/omp'); // {key: 'pair_style lj/cut/omp', package: 'OPENMP', ...}
 * styleExists('fix', 'nvt');              // true
 * searchCommands('lagevin')[0].key;       // 'fix langevin'
 * ```
 */

